import pytest

from terragrunt_generator.variables import Variable
from terragrunt_generator.yaml import (
    Block,
    format_description,
    get_yaml,
    merge_level,
    merge_yaml_strings,
    split_level,
)


@pytest.mark.parametrize(
    "description, indent, expected",
    [
        (
            "This is a description.",
            "    ",
            "This is a description.",
        ),
        (
            "This is a description.\nWith a second line.",
            "    ",
            "This is a description.\n    # With a second line.",
        ),
        (
            "First line.\nSecond line.\nThird line.",
            "  ",
            "First line.\n  # Second line.\n  # Third line.",
        ),
        (
            "",
            "    ",
            "",
        ),
        (
            'Line with \\"escaped\\" quotes.',
            "    ",
            'Line with "escaped" quotes.',
        ),
    ],
)
def test_format_description(description, indent, expected):
    assert format_description(description, indent) == expected


def test_get_yaml():
    name: str = "test"
    variables = [
        Variable("mandatories", "mandatories"),
        Variable("optionals", "optionals", default="optional_value"),
        Variable("nullables", "nullables", default=None),
    ]
    resutls = get_yaml(name, variables)
    print(resutls)
    excepted = """test:
  enabled: true
  # mandatories - mandatories
  mandatories: 
  # optionals - optionals
  # optionals: "optional_value"
  # nullables - nullables
  # nullables: 
"""
    assert resutls == excepted


def test_merge_yaml_strings():
    yaml1 = """gke:
  cluster:
    enabled: true
    # required - required value
    required:
    # optional - optional value
    # optional: "optional"
    # nullable - nullable value
    # nullable:
"""

    yaml2 = """gke:
  helper:
    enabled: true
    # required - required value
    required:
    # optional - optional value
    # optional: "optional"
    # nullable - nullable value
    # nullable:
"""

    result = merge_yaml_strings(yaml1, yaml2)

    assert "cluster:" in result
    assert "helper:" in result
    assert 'optional: "optional"' in result


def test_merge_yaml_strings_with_blank_lines_inside_blocks():
    yaml1 = """gke:
  cluster:
    enabled: true

    # required - required value
    required:

    # optional - optional value
    # optional: "optional"
"""
    yaml2 = """gke:
  cluster:
    # additional setting
    # another: "value"

  helper:
    enabled: true
"""

    result = merge_yaml_strings(yaml1, yaml2)

    assert "enabled: true\n\n    # required - required value" in result
    assert "helper:" in result
    assert 'another: "value"' in result


def test_merge_yaml_strings_with_other_keys():
    yaml1 = """# Generated by terragrunt-generator
# Do not edit manually

test:
  cluster:
    enabled: true
"""
    yaml2 = """gke:
  helper:
    enabled: true
"""

    result = merge_yaml_strings(yaml1, yaml2)

    assert "# Generated by terragrunt-generator" in result
    assert "test:" in result
    assert "cluster:" in result
    assert "gke:" in result
    assert "helper:" in result


def test_merge_yaml_strings_ends_with_block_without_trailing_line():
    yaml1 = """alpha:
  setting: true
beta:
  active: false"""
    yaml2 = """gamma:
  value: 123"""

    result = merge_yaml_strings(yaml1, yaml2)

    assert "alpha:" in result
    assert "beta:" in result
    assert "gamma:" in result
    assert "value: 123" in result


def test_merge_yaml_strings_with_same_content():
    yaml1 = """test:
  alpha:
    beta:
      value: 123"""
    yaml2 = """test:
  alpha:
    gamma:
      value: 123"""

    result = merge_yaml_strings(yaml1, yaml2)

    expected = """test:
  alpha:
    beta:
      value: 123
    gamma:
      value: 123"""

    assert result.strip() == expected.strip()


def test_split_level_separates_the_leading_lines_from_the_blocks():
    lines = ["# note", "x: 1", "a:", "  # inside", "  y: 2", "b:", "  z: 3"]

    leading, blocks = split_level(lines, 0)

    assert leading == ["# note", "x: 1"]
    assert list(blocks) == ["a:", "b:"]
    assert blocks["a:"] == Block("a:", ["  # inside", "  y: 2"])
    assert blocks["b:"].lines == ["b:", "  z: 3"]


def test_split_level_only_keys_a_level_at_its_indent():
    leading, blocks = split_level(["  a:", "    b:", "  c:"], 2)

    assert leading == []
    assert list(blocks) == ["a:", "c:"]
    assert blocks["a:"].body == ["    b:"]


def test_split_level_ignores_commented_keys_and_scalars():
    leading, blocks = split_level(["# a:", "b: 1", "c:"], 0)

    assert leading == ["# a:", "b: 1"]
    assert list(blocks) == ["c:"]


def test_split_level_keeps_the_scalars_that_follow_a_block_with_it():
    _, blocks = split_level(["a:", "  b:", "    x: 1", "  y: 2"], 0)

    assert blocks["a:"].body == ["  b:", "    x: 1", "  y: 2"]


def test_merge_level_keeps_the_values_of_the_existing_lines():
    merged = merge_level(["a:", "  x: kept"], ["a:", "  x: replaced"], 0)

    assert "  x: kept" in merged
    assert "  x: replaced" in merged
    assert merged.index("  x: kept") < merged.index("  x: replaced")


def test_merge_level_merges_the_keys_of_both_levels_one_level_down():
    merged = merge_level(
        ["a:", "  b:", "    x: 1"], ["a:", "  c:", "    y: 2", "  b:", "    # new"], 0
    )

    assert merged == [
        "a:",
        "  b:",
        "    x: 1",
        "    # new",
        "  c:",
        "    y: 2",
    ]


def test_merge_level_appends_the_keys_that_only_the_new_lines_hold():
    merged = merge_level(["a:", "  x: 1"], ["b:", "  y: 2"], 0)

    assert merged == ["a:", "  x: 1", "b:", "  y: 2"]


def test_merge_level_keeps_the_leading_lines_of_the_existing_ones_first():
    merged = merge_level(["# note", "a:"], ["b:"], 0)

    assert merged == ["# note", "a:", "b:"]


def test_merge_level_adds_a_new_line_once():
    merged = merge_level(["a:"], ["a:", "  # new", "  # new"], 0)

    assert merged == ["a:", "  # new"]


def test_merge_level_without_new_lines_changes_nothing():
    lines = ["# note", "a:", "  b:", "    x: 1"]

    assert merge_level(lines, [], 0) == lines
    assert merge_level(lines, lines, 0) == lines


@pytest.mark.parametrize(
    ("default", "rendered"),
    [
        (False, "false"),
        (0, "0"),
        ("", '""'),
        ([], "[]"),
        ({}, "{}"),
        (True, "true"),
        (3, "3"),
    ],
)
def test_get_yaml_keeps_the_falsy_defaults(default, rendered):
    results = get_yaml("test", [Variable("flag", "a flag", default=default)])

    assert f"  # flag: {rendered}\n" in results


def test_get_yaml_leaves_the_mandatory_and_nullable_values_empty():
    results = get_yaml(
        "test",
        [Variable("required", "r"), Variable("nullable", "n", default=None)],
    )

    assert "  required: \n" in results
    assert "  # nullable: \n" in results
